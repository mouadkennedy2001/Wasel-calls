let current = localStorage.getItem('wasel.lang') === 'en' ? 'en' : 'ar';

export function setLanguage(lang) {
  const next = lang === 'en' ? 'en' : 'ar';
  const changed = next !== current;
  current = next;
  localStorage.setItem('wasel.lang', current);
  document.documentElement.lang = current;
  document.documentElement.dir = current === 'ar' ? 'rtl' : 'ltr';
  if (changed) window.dispatchEvent(new CustomEvent('wasel:language', { detail: { language: current } }));
}

export function getLanguage() { return current; }
export function t(key) {
  const dict = current === 'ar' ? AR : EN;
  return dict[key] || (EN[key] || key);
}
